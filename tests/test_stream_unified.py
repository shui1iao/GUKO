class TransportTest(unittest.IsolatedAsyncioTestCase):
    async def test_same_existing_auth_binary_upload_and_scoped_cleanup(self):
        calls=[]
        def ssh(server,cmd,tty=False):return ['fixture-ssh',cmd]
        def env(server):return {'FIXTURE_AUTH':'injected-not-logged'}
        async def run(args,**kw):
            calls.append((args,kw))
            if 'uname -m' in args[1]:return 0,'x86_64\n',''
            if 'exec "$work/probe"' in args[1]:return 1,raw(),'mock warning'
            return 0,'',''
        payload=b'OFFLINE native payload';digest=hashlib.sha256(payload).hexdigest()
        with patch.object(u.tool_sources,'stream_source',return_value=(payload,{'binary':{'sha256':digest}})):
            code,text,err,cleanup=await u.remote_run({},ssh,env,runner=run)
        self.assertEqual(code,1);self.assertIsNone(cleanup);self.assertEqual(len(calls),3)
        self.assertEqual(hashlib.sha256(calls[1][1]['payload']).hexdigest(),digest)
        self.assertEqual(calls[1][1]['env'],{'FIXTURE_AUTH':'injected-not-logged'})
        self.assertNotIn('--region',calls[1][0][1]);self.assertIn('/proc/$pid/exe',calls[2][0][1]);self.assertNotIn('pkill',''.join(call[0][1] for call in calls))
